// app/lib/dateRange.ts
//
// ============================================================
// 目撃日の許容範囲（2026-07-26 新設）
//
// 投稿フォームのカレンダーと、APIルート側の検証の「両方」で使う。
// 同じ計算を2箇所に書くと必ずズレるため、ここに一本化している。
//
// ★必ず日本時間（JST = UTC+9）で「今日」を決めること★
//
// Vercelのサーバーは通常UTCで動く。サーバーがそのまま new Date() から
// 「今日」を計算すると、日本時間の朝0時〜9時の間は前日を「今日」と
// 判断してしまう。その状態で未来日付を弾くと、日本の利用者が朝に
// 「今日ゴキブリを見た」と投稿したときにサーバーから拒否される
// （カレンダーでは選べるのに送信できない、という状態になる）。
//
// ブラウザ側も同じ関数を使うことで、カレンダーで選べる範囲と
// サーバーが受け付ける範囲を完全に一致させている。端末のタイムゾーンが
// 日本以外に設定されていてもズレない。
// ============================================================

// ------------------------------------------------------------
// 目撃日として受け付ける過去の上限（年）
// ★「3年より前の情報は載らない」という運用方針。
//   変更するときはこの数値だけを書き換えればよい。
// ------------------------------------------------------------
export const MAX_PAST_YEARS = 3;

const JST_OFFSET_MS = 9 * 60 * 60 * 1000;

// ------------------------------------------------------------
// 日本時間での日付を "YYYY-MM-DD" 形式で返す。
// yearsAgo に年数を渡すと、その年数だけ過去の日付を返す。
//
// 仕組み：エポック時刻に9時間足してからUTCとして読むと、
// 日本時間の壁時計と同じ値になる。
//
// ★うるう日について：2028-02-29 の3年前は 2025-02-29 で、存在しない。
//   その場合 setUTCFullYear は 2025-03-01 に繰り上げる。1日だけ
//   厳しくなるが、実害はないためそのままにしている。
// ------------------------------------------------------------
export function jstDateString(yearsAgo = 0): string {
  const jst = new Date(Date.now() + JST_OFFSET_MS);
  if (yearsAgo !== 0) {
    jst.setUTCFullYear(jst.getUTCFullYear() - yearsAgo);
  }
  return jst.toISOString().slice(0, 10);
}

// カレンダーの上限（＝日本時間の今日）
export function latestAllowedDate(): string {
  return jstDateString();
}

// カレンダーの下限（＝日本時間の MAX_PAST_YEARS 年前）
export function oldestAllowedDate(): string {
  return jstDateString(MAX_PAST_YEARS);
}

// ------------------------------------------------------------
// 範囲外かどうかを判定する。範囲内なら null を返す。
//
// ★"YYYY-MM-DD" の文字列は、辞書順の比較がそのまま日付の前後関係に
//   なる（桁が固定でゼロ埋めされているため）。Dateに変換すると
//   タイムゾーンの解釈が絡んで1日ズレる原因になるので、
//   文字列のまま比較している。
// ★呼び出す前に "YYYY-MM-DD" 形式であることを確認しておくこと。
// ------------------------------------------------------------
export function checkOccurredOnRange(
  occurredOn: string
): "future" | "too_old" | null {
  if (occurredOn > latestAllowedDate()) return "future";
  if (occurredOn < oldestAllowedDate()) return "too_old";
  return null;
}